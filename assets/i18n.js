window.getPortfolioLanguage = () => {
  try {
    const saved = window.localStorage.getItem("mate-portfolio-language");
    if (saved === "hr" || saved === "en") return saved;
  } catch (error) {
    console.info("Language preference storage is unavailable.", error);
  }
  return new URLSearchParams(window.location.search).get("lang") === "en" ? "en" : "hr";
};

window.setPortfolioLanguage = (language) => {
  const selected = language === "en" ? "en" : "hr";
  try {
    window.localStorage.setItem("mate-portfolio-language", selected);
  } catch (error) {
    console.info("Language preference could not be saved.", error);
  }
  window.renderPortfolioLanguage(selected);
};
